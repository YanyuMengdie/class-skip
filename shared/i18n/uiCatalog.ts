const originalText = new WeakMap<Text, string>();
const originalAttributes = new WeakMap<Element, Map<string, string>>();
const LOCALIZED_ATTRIBUTES = ['placeholder', 'title', 'aria-label'] as const;
const SHORT_TEXT_UI_PARENTS = new Set(['BUTTON', 'LABEL', 'OPTION', 'H1', 'H2', 'H3', 'H4', 'H5', 'H6', 'NAV', 'ASIDE']);
const ALWAYS_TRANSLATE_SHORT = new Set(['起', '止', '页', '项', '第', '共', '证据', '分']);

const isPreservedContent = (element: Element | null): boolean => Boolean(element?.closest(
  '[data-preserve-language="true"], .prose, .markdown-body, textarea, script, style, code, pre',
));

const translateTextNode = (node: Text): void => {
  const parent = node.parentElement;
  if (!parent || isPreservedContent(parent)) return;
  const raw = node.data;
  const trimmed = raw.trim();
  const translated = ENGLISH_UI[trimmed];
  if (!translated) return;
  const chineseLength = (trimmed.match(/[\u3400-\u9fff]/g) ?? []).length;
  if (chineseLength <= 3 && !ALWAYS_TRANSLATE_SHORT.has(trimmed) && !SHORT_TEXT_UI_PARENTS.has(parent.tagName) && !parent.closest('button, label, nav, aside, [role="button"], [role="tab"]')) return;
  if (!originalText.has(node)) originalText.set(node, raw);
  node.data = `${raw.match(/^\s*/)?.[0] ?? ''}${translated}${raw.match(/\s*$/)?.[0] ?? ''}`;
};

const translateElement = (element: Element): void => {
  if (isPreservedContent(element)) return;
  for (const attribute of LOCALIZED_ATTRIBUTES) {
    const raw = element.getAttribute(attribute);
    if (!raw) continue;
    const translated = ENGLISH_UI[raw.trim()];
    if (!translated) continue;
    let originals = originalAttributes.get(element);
    if (!originals) {
      originals = new Map();
      originalAttributes.set(element, originals);
    }
    if (!originals.has(attribute)) originals.set(attribute, raw);
    element.setAttribute(attribute, translated);
  }
  for (const child of Array.from(element.childNodes)) {
    if (child.nodeType === Node.TEXT_NODE) translateTextNode(child as Text);
    else if (child.nodeType === Node.ELEMENT_NODE) translateElement(child as Element);
  }
};

const restoreElement = (element: Element): void => {
  const attributes = originalAttributes.get(element);
  attributes?.forEach((value, name) => element.setAttribute(name, value));
  originalAttributes.delete(element);
  for (const child of Array.from(element.childNodes)) {
    if (child.nodeType === Node.TEXT_NODE) {
      const text = child as Text;
      const value = originalText.get(text);
      if (value !== undefined) {
        text.data = value;
        originalText.delete(text);
      }
    } else if (child.nodeType === Node.ELEMENT_NODE) {
      restoreElement(child as Element);
    }
  }
};

export const installLegacyUiLocalization = (language: AppLanguage): (() => void) => {
  if (typeof document === 'undefined' || !document.body) return () => {};
  if (language === 'zh-CN') {
    restoreElement(document.body);
    return () => {};
  }

  translateElement(document.body);
  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === 'characterData') translateTextNode(mutation.target as Text);
      for (const node of Array.from(mutation.addedNodes)) {
        if (node.nodeType === Node.TEXT_NODE) translateTextNode(node as Text);
        else if (node.nodeType === Node.ELEMENT_NODE) translateElement(node as Element);
      }
      if (mutation.type === 'attributes' && mutation.target instanceof Element) translateElement(mutation.target);
    }
  });
  observer.observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: [...LOCALIZED_ATTRIBUTES],
  });
  return () => observer.disconnect();
};

export const translateKnownUiText = (text: string, language: AppLanguage): string => (
  language === 'en' ? (ENGLISH_UI[text] ?? text) : text
);
